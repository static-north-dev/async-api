using System.Text;
using System.Text.Json;

namespace StaticNorth.AsyncApi.Generator.SourceGeneration.Client;

internal sealed class ClientContractEmitter(ContractNode root, ClientOptions options, bool clientAvailable)
{
    private readonly ContractReferences _references = new(root);
    private readonly HashSet<string> _symbols = new(StringComparer.Ordinal);

    internal (string Source, string[] Symbols) Write(CancellationToken cancellationToken)
    {
        var schemas = new SchemaEmitter(_references, _symbols);
        var source = new StringBuilder();
        var operations = root.Field("operations");
        var channels = root.Field("channels");

        if (channels.Exists)
        {
            foreach (var (_, channel) in channels.Fields())
            {
                channel.Require(JsonValueKind.Object);
            }
        }

        if (operations.Exists)
        {
            foreach (var (id, operation) in operations.Fields())
            {
                cancellationToken.ThrowIfCancellationRequested();
                WriteOperation(source, schemas, channels, id, _references.ResolveObject(operation));
            }
        }

        foreach (var declaration in schemas.Declarations)
        {
            source
                .Append('\n')
                .Append(declaration);
        }

        if (source.Length == 0)
        {
            return ("", []);
        }

        source.Insert(0, $"// <auto-generated/>\n#nullable enable\n\nnamespace {options.Namespace};\n");
        var symbols = _symbols
            .OrderBy(symbol => symbol, StringComparer.Ordinal)
            .ToArray();
        return (source.ToString(), symbols);
    }

    private void WriteOperation(StringBuilder source, SchemaEmitter schemas, ContractNode channels, string id, ContractNode operation)
    {
        var action = operation.Field("action");
        var sending = action.String() switch
        {
            "send" => true,
            "receive" => false,
            _ => throw new ContractException(action.Path, "expected 'send' or 'receive'")
        };

        if ((sending && !options.Subscribers) || (!sending && !options.Publishers))
        {
            return;
        }

        if (operation.Field("reply").Exists)
        {
            throw new ContractException(operation.Path, "request/reply operations are unsupported", unsupported: true);
        }

        var channelReference = operation.Field("channel");
        var reference = channelReference.Field("$ref");
        var channelPath = ContractReferences.ReadPointer(reference);

        if (channelPath.Length != 2 || channelPath[0] != "channels")
        {
            throw new ContractException(reference.Path, "operation channel must point to a root channel");
        }

        var channelId = channelPath[1];
        var channel = _references.ResolveObject(channels.Field(channelId));
        var channelMessages = channel.Field("messages");
        var selected = SelectMessages(operation.Field("messages"), channelMessages, channelId);
        var stem = ClientNames.Identifier(id);
        var direction = sending ? "Subscriber" : "Publisher";
        var interfaceName = $"I{stem}{direction}";
        var metadataName = stem + "Metadata";
        var clientName = stem + direction;
        Reserve(operation, interfaceName);
        Reserve(operation, metadataName);

        if (clientAvailable)
        {
            Reserve(operation, clientName);
        }

        var address = channel.Field("address");
        var channelAddress = address.Exists && address.Kind != JsonValueKind.Null ? address.String() : null;
        var methods = new HashSet<string>(StringComparer.Ordinal) { interfaceName };
        var metadata = new HashSet<string>(StringComparer.Ordinal)
        {
            metadataName, "OperationId", "DocumentAction", "ChannelId", "ChannelAddress", "ChannelBindingsJson", "OperationBindingsJson"
        };
        var bindings = new StringBuilder();
        var routeFields = new StringBuilder();
        var routeInitializers = new StringBuilder();
        var implementations = new StringBuilder();
        source.Append($"\npublic interface {interfaceName}\n{{\n");

        foreach (var (key, node) in selected)
        {
            var message = _references.ResolveObject(node);
            var payload = message.Field("payload");
            var content = message.Field("contentType");
            var defaultContent = root.Field("defaultContentType");
            var contentType = content.Exists ? content.String() : defaultContent.Exists ? defaultContent.String() : "application/json";
            var suffix = ClientNames.Identifier(key);
            var method = (sending ? "Subscribe" : "Publish") + suffix + "Async";

            if (!methods.Add(method))
            {
                throw new ContractException(node.Path, $"generated method '{method}' conflicts with another member");
            }

            if (payload.Exists && !IsJsonContentType(contentType))
            {
                throw new ContractException(payload.Path, $"payload content type '{contentType}' is unsupported", unsupported: true);
            }

            var messageName = ComponentName(message) ?? suffix;
            var type = payload.Exists ? schemas.TypeOf(payload, options.ModelPrefix + ClientNames.Identifier(messageName)) : null;
            const string cancellation = "global::System.Threading.CancellationToken cancellationToken = default";
            var arguments = type is null ? "" : type + " message, ";
            string signature;

            if (sending)
            {
                var handlerArguments = type is null ? "" : type + ", ";
                var handler = $"global::System.Func<{handlerArguments}global::System.Threading.CancellationToken, global::System.Threading.Tasks.ValueTask> handler";
                signature = $"global::System.Threading.Tasks.ValueTask<global::System.IAsyncDisposable> {method}({handler}, {cancellation})";
            }
            else
            {
                signature = $"global::System.Threading.Tasks.ValueTask {method}({arguments}{cancellation})";
            }

            source.Append($"    {signature};\n");

            if (clientAvailable)
            {
                var field = "_route" + suffix;
                WriteRoute(routeFields, routeInitializers, field, metadataName, suffix);
                WriteImplementation(implementations, signature, sending, type, field);
            }

            MessageConstant(bindings, metadata, node, suffix + "MessageKey", key);
            MessageConstant(bindings, metadata, node, suffix + "ContentType", contentType);
            MessageConstant(bindings, metadata, node, suffix + "MessageBindingsJson", BindingJson(message));
            MessageConstant(bindings, metadata, node, suffix + "HeadersJson", RawJson(message.Field("headers")));
        }

        source.Append($"}}\n\npublic static class {metadataName}\n{{\n");
        Constant(source, "OperationId", id);
        Constant(source, "DocumentAction", sending ? "send" : "receive");
        Constant(source, "ChannelId", channelId);
        Constant(source, "ChannelAddress", channelAddress);
        Constant(source, "ChannelBindingsJson", BindingJson(channel));
        Constant(source, "OperationBindingsJson", BindingJson(operation));
        source
            .Append(bindings)
            .Append("}\n");

        if (clientAvailable)
        {
            WriteClient(source, routeFields, routeInitializers, implementations,
                clientName, interfaceName, metadataName, channelAddress);
        }
    }

    private static void WriteImplementation(
        StringBuilder source, string signature, bool sending, string? type, string routeField)
    {
        var method = sending ? "SubscribeAsync" : "PublishAsync";
        var arguments = sending ? "handler, " : "";

        if (type is not null)
        {
            var allowsNull = type.EndsWith("?", StringComparison.Ordinal) ? "true" : "false";
            method += $"<{type}>";
            arguments = $"{(sending ? "handler" : "message")}, {allowsNull}, ";
        }

        source.Append($$"""

                public {{signature}}
                {
                    return _client.{{method}}({{routeField}}, {{arguments}}cancellationToken);
                }

            """);
    }

    private static void WriteRoute(StringBuilder fields, StringBuilder initializers, string field, string metadata, string suffix)
    {
        fields.Append($"    private readonly global::StaticNorth.AsyncApi.Core.Transport.AsyncApiMessageRoute {field};\n");
        initializers.Append($$"""

                    {{field}} = new global::StaticNorth.AsyncApi.Core.Transport.AsyncApiMessageRoute(
                        address,
                        {{metadata}}.{{suffix}}MessageKey,
                        {{metadata}}.OperationId,
                        {{metadata}}.{{suffix}}ContentType,
                        {{metadata}}.ChannelBindingsJson,
                        {{metadata}}.OperationBindingsJson,
                        {{metadata}}.{{suffix}}MessageBindingsJson);
            """);
    }

    private static void WriteClient(
        StringBuilder source,
        StringBuilder routeFields,
        StringBuilder routeInitializers,
        StringBuilder implementations,
        string name,
        string contract,
        string metadata,
        string? address)
    {
        source.Append($"\npublic sealed class {name} : {contract}\n{{\n");

        if (routeFields.Length > 0)
        {
            var defaultAddress = string.IsNullOrWhiteSpace(address) || address!.IndexOfAny(['{', '}']) >= 0 ? "" : " = null";
            source.Append("    private readonly global::StaticNorth.AsyncApi.Client.Transport.AsyncApiJsonClient _client;\n");
            source.Append(routeFields);
            source.Append($$"""

                    public {{name}}(
                        global::StaticNorth.AsyncApi.Core.Transport.IAsyncApiTransport transport,
                        string? channelAddress{{defaultAddress}},
                        global::System.Text.Json.JsonSerializerOptions? serializerOptions = null)
                    {
                        _client = new global::StaticNorth.AsyncApi.Client.Transport.AsyncApiJsonClient(transport, serializerOptions);
                        var address = global::StaticNorth.AsyncApi.Client.Transport.AsyncApiJsonClient.ResolveAddress({{metadata}}.ChannelAddress, channelAddress);
                """);
            source.Append(routeInitializers);
            source.Append("""

                    }

                """);
            source.Append(implementations);
        }

        source.Append("}\n");
    }

    private static IEnumerable<(string Name, ContractNode Node)> SelectMessages(
        ContractNode selection,
        ContractNode channelMessages,
        string channelId)
    {
        if (!selection.Exists)
        {
            return channelMessages.Exists ? channelMessages.Fields() : [];
        }

        var selected = new SortedDictionary<string, ContractNode>(StringComparer.Ordinal);

        foreach (var item in selection.Items())
        {
            var reference = item.Field("$ref");
            var segments = ContractReferences.ReadPointer(reference);

            if (segments.Length != 4 || segments[0] != "channels" || segments[1] != channelId || segments[2] != "messages")
            {
                throw new ContractException(reference.Path, "operation messages must refer to keys on the operation's channel");
            }

            var key = segments[3];
            var message = channelMessages.Exists ? channelMessages.Field(key) : default;

            if (!message.Exists || selected.ContainsKey(key))
            {
                throw new ContractException(reference.Path, $"missing or repeated channel message '{key}'");
            }

            selected.Add(key, message);
        }

        return selected.Select(pair => (pair.Key, pair.Value));
    }

    private static string? ComponentName(ContractNode message)
    {
        const string prefix = "#/components/messages/";
        return message.Path.StartsWith(prefix, StringComparison.Ordinal) ?
            Uri.UnescapeDataString(message.Path.Substring(prefix.Length)) : null;
    }

    private static bool IsJsonContentType(string contentType)
    {
        var mediaType = contentType.Split(';')[0].Trim();
        return mediaType.Equals("application/json", StringComparison.OrdinalIgnoreCase) ||
            mediaType.EndsWith("+json", StringComparison.OrdinalIgnoreCase);
    }

    private string? BindingJson(ContractNode node)
    {
        var bindings = node.Field("bindings");
        return bindings.Exists ? RawJson(_references.ResolveObject(bindings)) : null;
    }

    private static string? RawJson(ContractNode node)
    {
        return node.Exists ? node.Value.GetRawText() : null;
    }

    private static void Constant(StringBuilder source, string name, string? value)
    {
        var declaration = value is null ? "string?" : "string";
        var expression = value is null ? "null" : ClientNames.Literal(value);
        source.Append($"    public const {declaration} {name} = {expression};\n");
    }

    private static void MessageConstant(StringBuilder source, HashSet<string> names, ContractNode node, string name, string? value)
    {
        if (!names.Add(name))
        {
            throw new ContractException(node.Path, $"generated metadata name '{name}' conflicts with another member");
        }

        Constant(source, name, value);
    }

    private void Reserve(ContractNode node, string name)
    {
        if (!_symbols.Add(name))
        {
            throw new ContractException(node.Path, $"generated symbol '{name}' conflicts with another declaration");
        }
    }
}
